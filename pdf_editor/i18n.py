def _language_code(value: str | None) -> str | None:
    if not value:
        return None
    code = value.strip().strip('"').split(":", 1)[0]
    code = re.split(r"[-_.@]", code, maxsplit=1)[0].lower()
    return code if code in SUPPORTED_LANGUAGES else None


def detect_language() -> str:
    candidates: list[str | None] = []

    if sys.platform == "darwin":
        try:
            result = subprocess.run(
                ["defaults", "read", "-g", "AppleLanguages"],
                capture_output=True,
                text=True,
                check=False,
                timeout=1,
            )
            candidates.extend(re.findall(r'"([^"]+)"', result.stdout))
        except (OSError, subprocess.TimeoutExpired):
            pass

    try:
        candidates.append(locale.getlocale()[0])
    except ValueError:
        pass
    candidates.extend(
        os.environ.get(name)
        for name in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG")
    )

    for candidate in candidates:
        code = _language_code(candidate)
        if code:
            return code
    return "en"


LANGUAGE = detect_language()


def tr(key: str, **values: object) -> str:
    template = TRANSLATIONS.get(LANGUAGE, TRANSLATIONS["en"]).get(
        key, TRANSLATIONS["en"].get(key, key)
    )
    return template.format(**values)
